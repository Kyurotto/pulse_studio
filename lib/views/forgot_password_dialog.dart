import 'dart:async';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

import '../auth/password_recovery_api.dart';
import '../auth/saved_credential_store.dart';
import '../data/local_database.dart';
import '../theme/app_theme.dart';

enum ForgotPasswordStep { enterEmail, verifyCode, newPassword, success }

/// Account and OTP operations used by [ForgotPasswordDialog].
///
/// Production talks to local SQLite plus the deployed Pulse Studio recovery
/// backend. Tests subclass this to exercise the dialog without network or
/// platform plugins.
class ForgotPasswordAccountStore {
  ForgotPasswordAccountStore({PasswordRecoveryApi? api})
    : _api = api ?? PasswordRecoveryApi();

  final PasswordRecoveryApi _api;

  Future<Map<String, Object?>?> findByEmail(String email) {
    return LocalDatabase.instance.getUserByEmail(email);
  }

  Future<PasswordRecoveryRequestResult> requestOtp(String email) {
    return _api.requestPasswordReset(email);
  }

  Future<PasswordRecoveryVerifyResult> verifyOtp({
    required String email,
    required String code,
    required String requestId,
  }) {
    return _api.verifyPasswordResetOtp(
      email: email,
      code: code,
      requestId: requestId,
    );
  }

  Future<void> completeReset({
    required String requestId,
    required String resetToken,
    required String newPassword,
  }) {
    return _api.completePasswordReset(
      requestId: requestId,
      resetToken: resetToken,
      newPassword: newPassword,
    );
  }

  Future<void> updatePassword({
    required String id,
    required String newPassword,
  }) {
    return LocalDatabase.instance.updatePasswordHash(
      id: id,
      newPassword: newPassword,
    );
  }

  /// Keeps the reset account on the sign-in screen so it can autofill the
  /// password the user just chose.
  Future<void> rememberAccount({
    required String email,
    required String displayName,
  }) {
    return LocalDatabase.instance.saveRememberedAccount(
      email: email,
      displayName: displayName,
    );
  }

  /// Stores the new password in the device's encrypted credential storage.
  Future<void> savePassword({
    required String email,
    required String newPassword,
  }) {
    return SavedCredentialStore.instance.savePassword(email, newPassword);
  }
}

/// Password recovery for Pulse Studio accounts.
///
/// A 6-digit code is generated by the trusted backend and emailed to the
/// account's Gmail address. The new-password step is only shown after that
/// code is verified; the backend also issues a single-use reset token that is
/// consumed before the local SQLite password hash is changed.
class ForgotPasswordDialog extends StatefulWidget {
  final String? initialEmail;
  final ForgotPasswordAccountStore? accountStore;
  final ValueChanged<String>? onPasswordResetSuccess;

  const ForgotPasswordDialog({
    super.key,
    this.initialEmail,
    this.accountStore,
    this.onPasswordResetSuccess,
  });

  @override
  State<ForgotPasswordDialog> createState() => _ForgotPasswordDialogState();
}

class _ForgotPasswordDialogState extends State<ForgotPasswordDialog> {
  late final ForgotPasswordAccountStore _accounts;

  ForgotPasswordStep _currentStep = ForgotPasswordStep.enterEmail;

  final _emailController = TextEditingController();
  final _otpController = TextEditingController();
  final _passwordController = TextEditingController();
  final _confirmPasswordController = TextEditingController();

  final _formKeyEmail = GlobalKey<FormState>();
  final _formKeyOtp = GlobalKey<FormState>();
  final _formKeyPassword = GlobalKey<FormState>();

  bool _isBusy = false;
  String? _errorMessage;
  String? _infoMessage;

  bool _obscurePassword = true;
  bool _obscureConfirmPassword = true;

  String _confirmedEmail = '';
  String _confirmedDisplayName = '';
  String _requestId = '';
  String _resetToken = '';
  String _resetUserId = '';

  Timer? _expiryTimer;
  int _expirySecondsRemaining = 300; // 5 minutes

  Timer? _resendTimer;
  int _resendSecondsRemaining = 60; // 60 seconds

  @override
  void initState() {
    super.initState();
    _accounts = widget.accountStore ?? ForgotPasswordAccountStore();
    final initEmail = (widget.initialEmail ?? '').trim();
    if (initEmail.isNotEmpty) {
      _emailController.text = initEmail;
    }
  }

  @override
  void dispose() {
    _expiryTimer?.cancel();
    _resendTimer?.cancel();
    _emailController.dispose();
    _otpController.dispose();
    _passwordController.dispose();
    _confirmPasswordController.dispose();
    super.dispose();
  }

  void _startTimers() {
    _expiryTimer?.cancel();
    _resendTimer?.cancel();

    setState(() {
      _expirySecondsRemaining = 300;
      _resendSecondsRemaining = 60;
    });

    _expiryTimer = Timer.periodic(const Duration(seconds: 1), (timer) {
      if (!mounted) {
        timer.cancel();
        return;
      }
      if (_expirySecondsRemaining > 0) {
        setState(() => _expirySecondsRemaining--);
      } else {
        timer.cancel();
      }
    });

    _resendTimer = Timer.periodic(const Duration(seconds: 1), (timer) {
      if (!mounted) {
        timer.cancel();
        return;
      }
      if (_resendSecondsRemaining > 0) {
        setState(() => _resendSecondsRemaining--);
      } else {
        timer.cancel();
      }
    });
  }

  void _stopTimers() {
    _expiryTimer?.cancel();
    _resendTimer?.cancel();
  }

  String _maskEmail(String email) {
    final parts = email.split('@');
    if (parts.length != 2) return email;
    final name = parts[0];
    final domain = parts[1];
    if (name.length <= 2) {
      return '${name[0]}*@$domain';
    }
    return '${name.substring(0, 2)}${'*' * (name.length - 2)}@$domain';
  }

  String _formatTimer(int totalSeconds) {
    final minutes = totalSeconds ~/ 60;
    final seconds = totalSeconds % 60;
    return '${minutes.toString().padLeft(2, '0')}:'
        '${seconds.toString().padLeft(2, '0')}';
  }

  void _backToEmail() {
    _stopTimers();
    _otpController.clear();
    _passwordController.clear();
    _confirmPasswordController.clear();
    setState(() {
      _currentStep = ForgotPasswordStep.enterEmail;
      _isBusy = false;
      _errorMessage = null;
      _infoMessage = null;
      _requestId = '';
      _resetToken = '';
      _resetUserId = '';
    });
  }

  // ---------------------------------------------------------------------------
  // Step Actions
  // ---------------------------------------------------------------------------

  Future<void> _submitEmail() async {
    if (!_formKeyEmail.currentState!.validate()) return;

    final email = _emailController.text.trim().toLowerCase();
    setState(() {
      _isBusy = true;
      _errorMessage = null;
      _infoMessage = null;
    });

    try {
      final account = await _accounts.findByEmail(email);
      if (!mounted) return;

      if (account == null) {
        setState(() {
          _isBusy = false;
          _errorMessage =
              'No Pulse Studio account found for $email. '
              'Check the address or create a new account.';
        });
        return;
      }

      final provider = (account['auth_provider'] as String? ?? '')
          .toLowerCase();
      if (provider.isNotEmpty && provider != 'password') {
        setState(() {
          _isBusy = false;
          _errorMessage =
              'This account signs in with $provider. '
              'Use that sign-in method instead of a password.';
        });
        return;
      }

      final result = await _accounts.requestOtp(email);
      if (!mounted) return;

      _confirmedEmail = email;
      _confirmedDisplayName = (account['display_name'] as String? ?? '').trim();
      _resetUserId = (account['id'] as String?) ?? '';
      _requestId = result.requestId;
      _startTimers();
      setState(() {
        _isBusy = false;
        _currentStep = ForgotPasswordStep.verifyCode;
        _infoMessage = 'We sent a 6-digit verification code to $email.';
      });
    } on PasswordRecoveryException catch (e) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = e.message;
      });
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = 'Unable to send a verification code. Please try again.';
      });
    }
  }

  Future<void> _resendCode() async {
    if (_resendSecondsRemaining > 0 || _isBusy) return;
    setState(() {
      _isBusy = true;
      _errorMessage = null;
      _infoMessage = null;
    });

    try {
      final result = await _accounts.requestOtp(_confirmedEmail);
      if (!mounted) return;
      _requestId = result.requestId;
      _otpController.clear();
      _startTimers();
      setState(() {
        _isBusy = false;
        _infoMessage = 'A new verification code has been sent.';
      });
    } on PasswordRecoveryException catch (e) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = e.message;
      });
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = 'Unable to resend the code. Please try again.';
      });
    }
  }

  Future<void> _submitOtp() async {
    if (!_formKeyOtp.currentState!.validate()) return;
    if (_expirySecondsRemaining <= 0) {
      setState(() {
        _errorMessage =
            'Verification code has expired. Please request a new one.';
      });
      return;
    }

    setState(() {
      _isBusy = true;
      _errorMessage = null;
      _infoMessage = null;
    });

    try {
      final result = await _accounts.verifyOtp(
        email: _confirmedEmail,
        code: _otpController.text.trim(),
        requestId: _requestId,
      );
      if (!mounted) return;

      _resetToken = result.resetToken;
      _stopTimers();
      setState(() {
        _isBusy = false;
        _currentStep = ForgotPasswordStep.newPassword;
      });
    } on PasswordRecoveryException catch (e) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = e.message;
      });
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = 'Invalid verification code. Please try again.';
      });
    }
  }

  Future<void> _submitNewPassword() async {
    if (!_formKeyPassword.currentState!.validate()) return;

    if (_passwordController.text != _confirmPasswordController.text) {
      setState(() => _errorMessage = 'Passwords do not match.');
      return;
    }

    setState(() {
      _isBusy = true;
      _errorMessage = null;
      _infoMessage = null;
    });

    try {
      // The backend consumes the single-use token before the local hash is
      // changed, so a new password always requires a verified email code.
      await _accounts.completeReset(
        requestId: _requestId,
        resetToken: _resetToken,
        newPassword: _passwordController.text,
      );

      await _accounts.updatePassword(
        id: _resetUserId,
        newPassword: _passwordController.text,
      );

      // Remember the account and keep the new password in encrypted storage
      // so the sign-in screen can autofill it immediately. These are
      // best-effort: the backend token is already consumed and the local
      // hash is already changed, so a storage hiccup must not turn a
      // successful reset into an error.
      try {
        await _accounts.rememberAccount(
          email: _confirmedEmail,
          displayName: _confirmedDisplayName,
        );
        await _accounts.savePassword(
          email: _confirmedEmail,
          newPassword: _passwordController.text,
        );
        // Ask Android/iOS/browser password managers to offer saving the new
        // credential too, so it also participates in system autofill.
        TextInput.finishAutofillContext(shouldSave: true);
      } catch (_) {}

      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _currentStep = ForgotPasswordStep.success;
      });
    } on PasswordRecoveryException catch (e) {
      if (!mounted) return;
      if (e.code == 'invalid_reset_token') {
        _backToEmail();
        setState(() {
          _errorMessage =
              'Your verification expired. Please request a new code.';
        });
        return;
      }
      setState(() {
        _isBusy = false;
        _errorMessage = e.message;
      });
    } on ArgumentError {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = 'Use a password with at least 6 characters.';
      });
    } on StateError {
      if (!mounted) return;
      _backToEmail();
      setState(() {
        _errorMessage =
            'Verification succeeded but the password could not be saved. '
            'Please request a new code and try again.';
      });
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _isBusy = false;
        _errorMessage = 'Unable to update your password. Please try again.';
      });
    }
  }

  void _finishAndClose() {
    widget.onPasswordResetSuccess?.call(_confirmedEmail);
    Navigator.of(context).pop();
  }

  // ---------------------------------------------------------------------------
  // UI Builders
  // ---------------------------------------------------------------------------

  @override
  Widget build(BuildContext context) {
    return Dialog(
      backgroundColor: AppTheme.surface,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(20),
        side: const BorderSide(color: AppTheme.border),
      ),
      insetPadding: const EdgeInsets.symmetric(horizontal: 20, vertical: 24),
      child: ConstrainedBox(
        constraints: const BoxConstraints(maxWidth: 440),
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(28),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              _buildHeader(),
              const SizedBox(height: 18),
              if (_errorMessage != null)
                _buildAlertBox(_errorMessage!, isError: true),
              if (_infoMessage != null)
                _buildAlertBox(_infoMessage!, isError: false),
              const SizedBox(height: 8),
              _buildCurrentStepContent(),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildHeader() {
    String title;
    IconData icon;

    switch (_currentStep) {
      case ForgotPasswordStep.enterEmail:
        title = 'Forgot Password';
        icon = Icons.lock_reset_rounded;
        break;
      case ForgotPasswordStep.verifyCode:
        title = 'Verify Your Email';
        icon = Icons.mark_email_read_outlined;
        break;
      case ForgotPasswordStep.newPassword:
        title = 'Set New Password';
        icon = Icons.password_rounded;
        break;
      case ForgotPasswordStep.success:
        title = 'Password Reset Successfully!';
        icon = Icons.check_circle_outline_rounded;
        break;
    }

    return Column(
      children: [
        Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            Icon(icon, size: 30, color: AppTheme.primary),
            IconButton(
              icon: const Icon(
                Icons.close,
                size: 20,
                color: AppTheme.textSecondary,
              ),
              onPressed: _isBusy ? null : () => Navigator.of(context).pop(),
              splashRadius: 18,
            ),
          ],
        ),
        const SizedBox(height: 8),
        Align(
          alignment: Alignment.centerLeft,
          child: Text(
            title,
            style: const TextStyle(
              fontSize: 20,
              fontWeight: FontWeight.bold,
              color: AppTheme.textPrimary,
            ),
          ),
        ),
      ],
    );
  }

  Widget _buildAlertBox(String text, {required bool isError}) {
    final color = isError ? const Color(0xFFE57373) : AppTheme.accentGreen;
    final bg = isError ? const Color(0xFF2C1616) : const Color(0xFF162518);

    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
      decoration: BoxDecoration(
        color: bg,
        borderRadius: BorderRadius.circular(10),
        border: Border.all(color: color.withValues(alpha: 0.5)),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Icon(
            isError ? Icons.error_outline : Icons.info_outline,
            size: 18,
            color: color,
          ),
          const SizedBox(width: 10),
          Expanded(
            child: Text(
              text,
              style: TextStyle(fontSize: 12.5, color: color, height: 1.4),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildCurrentStepContent() {
    switch (_currentStep) {
      case ForgotPasswordStep.enterEmail:
        return _buildEmailStep();
      case ForgotPasswordStep.verifyCode:
        return _buildVerifyOtpStep();
      case ForgotPasswordStep.newPassword:
        return _buildNewPasswordStep();
      case ForgotPasswordStep.success:
        return _buildSuccessStep();
    }
  }

  // ---------------------------------------------------------------------------
  // Step 1: Email Entry
  // ---------------------------------------------------------------------------

  Widget _buildEmailStep() {
    return Form(
      key: _formKeyEmail,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          const Text(
            'Enter the email address you use for Pulse Studio. '
            'We will send a 6-digit verification code to your Gmail before '
            'you can set a new password.',
            style: TextStyle(
              fontSize: 13,
              color: AppTheme.textSecondary,
              height: 1.4,
            ),
          ),
          const SizedBox(height: 16),
          TextFormField(
            controller: _emailController,
            keyboardType: TextInputType.emailAddress,
            textInputAction: TextInputAction.done,
            autofillHints: const [AutofillHints.email],
            decoration: const InputDecoration(
              labelText: 'Gmail address',
              hintText: 'username@gmail.com',
              prefixIcon: Icon(Icons.email_outlined, size: 20),
            ),
            validator: (value) {
              final v = value?.trim().toLowerCase() ?? '';
              if (v.isEmpty) return 'Enter your Gmail address.';
              if (!v.endsWith('@gmail.com')) {
                return 'Please enter a valid @gmail.com address.';
              }
              final gmailRegex = RegExp(
                r'^[a-zA-Z0-9.!#$%&’*+/=?^_`{|}~-]+@gmail\.com$',
              );
              if (!gmailRegex.hasMatch(v)) {
                return 'Invalid Gmail format.';
              }
              return null;
            },
            onFieldSubmitted: (_) => _submitEmail(),
          ),
          const SizedBox(height: 20),
          ElevatedButton(
            onPressed: _isBusy ? null : _submitEmail,
            child: _isBusy
                ? const SizedBox(
                    height: 20,
                    width: 20,
                    child: CircularProgressIndicator(strokeWidth: 2),
                  )
                : const Text('Send verification code'),
          ),
        ],
      ),
    );
  }

  // ---------------------------------------------------------------------------
  // Step 2: OTP Verification
  // ---------------------------------------------------------------------------

  Widget _buildVerifyOtpStep() {
    return Form(
      key: _formKeyOtp,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Text(
            'We sent a 6-digit code to ${_maskEmail(_confirmedEmail)}. '
            'Enter it below to continue.',
            style: const TextStyle(
              fontSize: 13,
              color: AppTheme.textSecondary,
              height: 1.4,
            ),
          ),
          const SizedBox(height: 16),
          TextFormField(
            controller: _otpController,
            keyboardType: TextInputType.number,
            maxLength: 6,
            textInputAction: TextInputAction.done,
            textAlign: TextAlign.center,
            style: const TextStyle(
              fontSize: 14,
              letterSpacing: 3.0,
              fontWeight: FontWeight.w500,
              color: AppTheme.textPrimary,
            ),
            inputFormatters: [
              FilteringTextInputFormatter.digitsOnly,
              LengthLimitingTextInputFormatter(6),
            ],
            decoration: const InputDecoration(
              labelText: '6-digit verification code',
              hintText: '123456',
              counterText: '',
              prefixIcon: Icon(Icons.pin_outlined, size: 20),
            ),
            validator: (value) {
              final v = value?.trim() ?? '';
              if (v.length != 6 || int.tryParse(v) == null) {
                return 'Enter the 6-digit numeric code.';
              }
              return null;
            },
            onFieldSubmitted: (_) => _submitOtp(),
          ),
          const SizedBox(height: 12),
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(
                'Expires in: ${_formatTimer(_expirySecondsRemaining)}',
                style: TextStyle(
                  fontSize: 12,
                  color: _expirySecondsRemaining < 60
                      ? const Color(0xFFE57373)
                      : AppTheme.textSecondary,
                  fontWeight: FontWeight.w500,
                ),
              ),
              TextButton(
                onPressed: (_resendSecondsRemaining == 0 && !_isBusy)
                    ? _resendCode
                    : null,
                style: TextButton.styleFrom(
                  padding: EdgeInsets.zero,
                  minimumSize: Size.zero,
                  tapTargetSize: MaterialTapTargetSize.shrinkWrap,
                ),
                child: Text(
                  _resendSecondsRemaining > 0
                      ? 'Resend in ${_resendSecondsRemaining}s'
                      : 'Resend code',
                  style: TextStyle(
                    fontSize: 12,
                    color: _resendSecondsRemaining > 0
                        ? AppTheme.textMuted
                        : AppTheme.primary,
                    fontWeight: FontWeight.w600,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 8),
          Align(
            alignment: Alignment.centerLeft,
            child: TextButton(
              onPressed: _isBusy ? null : _backToEmail,
              style: TextButton.styleFrom(
                padding: EdgeInsets.zero,
                minimumSize: Size.zero,
                tapTargetSize: MaterialTapTargetSize.shrinkWrap,
              ),
              child: const Text(
                'Use a different email',
                style: TextStyle(
                  fontSize: 12,
                  color: AppTheme.primary,
                  fontWeight: FontWeight.w600,
                ),
              ),
            ),
          ),
          const SizedBox(height: 12),
          ElevatedButton(
            onPressed: _isBusy ? null : _submitOtp,
            child: _isBusy
                ? const SizedBox(
                    height: 20,
                    width: 20,
                    child: CircularProgressIndicator(strokeWidth: 2),
                  )
                : const Text('Verify code'),
          ),
        ],
      ),
    );
  }

  // ---------------------------------------------------------------------------
  // Step 3: New Password
  // ---------------------------------------------------------------------------

  Widget _buildNewPasswordStep() {
    return AutofillGroup(
      child: Form(
        key: _formKeyPassword,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Text(
              'Set a new password for $_confirmedEmail. '
              'Use at least 6 characters.',
              style: const TextStyle(
                fontSize: 13,
                color: AppTheme.textSecondary,
                height: 1.4,
              ),
            ),
            const SizedBox(height: 16),
            TextFormField(
              controller: _passwordController,
              obscureText: _obscurePassword,
              autofillHints: const [AutofillHints.newPassword],
              enableSuggestions: false,
              autocorrect: false,
              textInputAction: TextInputAction.next,
              decoration: InputDecoration(
                labelText: 'New password',
                prefixIcon: const Icon(Icons.lock_outline, size: 20),
                suffixIcon: IconButton(
                  icon: Icon(
                    _obscurePassword
                        ? Icons.visibility_off_outlined
                        : Icons.visibility_outlined,
                    size: 20,
                    color: AppTheme.textSecondary,
                  ),
                  onPressed: () =>
                      setState(() => _obscurePassword = !_obscurePassword),
                ),
              ),
              validator: (value) {
                if (value == null || value.length < 6) {
                  return 'Use at least 6 characters.';
                }
                return null;
              },
            ),
            const SizedBox(height: 14),
            TextFormField(
              controller: _confirmPasswordController,
              obscureText: _obscureConfirmPassword,
              autofillHints: const [AutofillHints.newPassword],
              enableSuggestions: false,
              autocorrect: false,
              textInputAction: TextInputAction.done,
              decoration: InputDecoration(
                labelText: 'Confirm new password',
                prefixIcon: const Icon(Icons.lock_reset_outlined, size: 20),
                suffixIcon: IconButton(
                  icon: Icon(
                    _obscureConfirmPassword
                        ? Icons.visibility_off_outlined
                        : Icons.visibility_outlined,
                    size: 20,
                    color: AppTheme.textSecondary,
                  ),
                  onPressed: () => setState(
                    () => _obscureConfirmPassword = !_obscureConfirmPassword,
                  ),
                ),
              ),
              validator: (value) {
                if (value == null || value.isEmpty) {
                  return 'Please confirm your password.';
                }
                if (value != _passwordController.text) {
                  return 'Passwords do not match.';
                }
                return null;
              },
              onFieldSubmitted: (_) => _submitNewPassword(),
            ),
            const SizedBox(height: 20),
            ElevatedButton(
              onPressed: _isBusy ? null : _submitNewPassword,
              child: _isBusy
                  ? const SizedBox(
                      height: 20,
                      width: 20,
                      child: CircularProgressIndicator(strokeWidth: 2),
                    )
                  : const Text('Reset password'),
            ),
          ],
        ),
      ),
    );
  }

  // ---------------------------------------------------------------------------
  // Step 4: Success
  // ---------------------------------------------------------------------------

  Widget _buildSuccessStep() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        const SizedBox(height: 12),
        const Center(
          child: Icon(
            Icons.check_circle_outline_rounded,
            size: 64,
            color: AppTheme.accentGreen,
          ),
        ),
